function Invoke-OwnerBuild
{
  param(
    [Parameter(Mandatory = $true)][string] $OutputDirectory,
    [Parameter(Mandatory = $true)][string] $ReportPath,
    [Parameter(Mandatory = $true)][string] $MaxCpuArgument,
    [Parameter(Mandatory = $true)][string] $Label
  )

  Write-Step $Label
  $args =
    "msbuild `"$ownerProjectPath`" /t:Rebuild /p:Configuration=$Configuration " +
    "/p:Xml2Doc_OutputDir=`"$OutputDirectory`" " +
    "/p:Xml2Doc_AggregateReportPath=`"$ReportPath`" " +
    "$MaxCpuArgument /nr:false /nodeReuse:false /v:minimal"
  Run-OrThrow -File "dotnet" -Args $args -Cwd $repo -ErrorPrefix "$Label failed."
}

Invoke-OwnerBuild -OutputDirectory $parallelDocs -ReportPath $parallelReport -MaxCpuArgument "/m" -Label "Parallel repository build"
Invoke-OwnerBuild -OutputDirectory $serialDocs -ReportPath $serialReport -MaxCpuArgument "/m:1" -Label "Serial repository build"

Write-Step "Comparing parallel and serial aggregate output"
Assert-True (Test-Path (Join-Path $parallelDocs "index.md")) "Parallel build did not generate index.md."
Assert-True (Test-Path (Join-Path $serialDocs "index.md")) "Serial build did not generate index.md."

$parallelSnapshot = Get-Snapshot $parallelDocs
$serialSnapshot = Get-Snapshot $serialDocs
Assert-SnapshotsEqual $parallelSnapshot $serialSnapshot

$index = Get-Content (Join-Path $parallelDocs "index.md") -Raw
$alphaIndex = $index.IndexOf("Alpha.Api.Widget", [StringComparison]::Ordinal)
$zuluIndex = $index.IndexOf("Zulu.Api.Widget", [StringComparison]::Ordinal)
Assert-True ($alphaIndex -ge 0) "Aggregate index does not contain Alpha.Api.Widget."
Assert-True ($zuluIndex -gt $alphaIndex) "Aggregate index is not in stable ordinal project/type order."

$reportModel = Get-Content $parallelReport -Raw | ConvertFrom-Json
Assert-True ($reportModel.xmlInputs.Count -eq 2) "Expected exactly two aggregate XML inputs in the report."
$reportedInputs = @($reportModel.xmlInputs)
$sortedInputs = @($reportedInputs | Sort-Object -CaseSensitive)
Assert-True (($reportedInputs -join "`n") -ceq ($sortedInputs -join "`n")) "Aggregate report XML inputs are not canonically ordered."

Write-Step "MSBuild repository aggregation integration completed successfully"
Write-Host "MSBuild aggregation integration OK. Artifacts: $runRoot"

