$ErrorActionPreference = "Stop"

function RepoRoot
{
  (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
}

function Write-Step([string] $Message)
{
  Write-Host ""
  Write-Host "==> $Message"
}

function Assert-True($Condition, [string] $Message)
{
  if (-not $Condition) { throw $Message }
}

function Run-Capture
{
  param(
    [Parameter(Mandatory = $true)][string] $FileName,
    [Parameter(Mandatory = $true)][string] $Arguments,
    [Parameter(Mandatory = $true)][string] $WorkingDirectory
  )

  $psi = [System.Diagnostics.ProcessStartInfo]::new()
  $psi.FileName = $FileName
  $psi.Arguments = $Arguments
  $psi.WorkingDirectory = $WorkingDirectory
  $psi.UseShellExecute = $false
  $psi.RedirectStandardOutput = $true
  $psi.RedirectStandardError = $true
  $psi.CreateNoWindow = $true

  $process = [System.Diagnostics.Process]::new()
  $process.StartInfo = $psi
  [void]$process.Start()
  $stdout = $process.StandardOutput.ReadToEnd()
  $stderr = $process.StandardError.ReadToEnd()
  $process.WaitForExit()

  [pscustomobject]@{
    ExitCode = $process.ExitCode
    StdOut = $stdout
    StdErr = $stderr
  }
}

function Run-OrThrow
{
  param(
    [Parameter(Mandatory = $true)][string] $File,
    [Parameter(Mandatory = $true)][string] $Args,
    [Parameter(Mandatory = $true)][string] $Cwd,
    [string] $ErrorPrefix = "Command failed"
  )

  Write-Host "    CMD: $File $Args"
  $result = Run-Capture -FileName $File -Arguments $Args -WorkingDirectory $Cwd
  if ($result.ExitCode -ne 0)
  {
    throw "$ErrorPrefix`n`nCMD: $File $Args`n`nSTDOUT:`n$($result.StdOut)`n`nSTDERR:`n$($result.StdErr)"
  }

  return $result
}

function Write-TextFile([string] $Path, [string] $Content)
{
  $directory = Split-Path $Path -Parent
  if ($directory -and -not (Test-Path $directory))
  {
    New-Item -ItemType Directory -Force -Path $directory | Out-Null
  }

  [System.IO.File]::WriteAllText($Path, $Content)
}

function Escape-Xml([string] $Value)
{
  [System.Security.SecurityElement]::Escape($Value)
}

function Get-Snapshot([string] $Root)
{
  $rootPath = (Resolve-Path $Root).Path.TrimEnd('\', '/')
  $snapshot = [ordered]@{}

  Get-ChildItem -Path $rootPath -Recurse -File |
    Sort-Object FullName |
    ForEach-Object {
      $relative = $_.FullName.Substring($rootPath.Length).TrimStart('\', '/') -replace '\\', '/'
      $snapshot[$relative] = (Get-FileHash -Algorithm SHA256 -LiteralPath $_.FullName).Hash
    }

  $snapshot
}

function Assert-SnapshotsEqual($Expected, $Actual)
{
  $expectedNames = @($Expected.Keys)
  $actualNames = @($Actual.Keys)
  Assert-True (($expectedNames -join "`n") -ceq ($actualNames -join "`n")) (
    "Generated file sets differ.`nExpected:`n$($expectedNames -join "`n")`nActual:`n$($actualNames -join "`n")")

  foreach ($name in $expectedNames)
  {
    Assert-True ($Expected[$name] -eq $Actual[$name]) "Generated bytes differ for '$name'."
  }
}

